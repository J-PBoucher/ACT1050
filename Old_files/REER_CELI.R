#### **REER : report d’impôt et arbitrage temporel** 

Le REER repose sur une logique simple : déduire aujourd’hui, imposer demain. La cotisation réduit le revenu imposable courant, mais les retraits seront entièrement imposés. L’intérêt réel ne vient pas du « gain fiscal » en soi, mais du décalage entre deux taux d’imposition : celui au moment de la cotisation et celui au moment du retrait.

::: {#exm-5 .custom}
  Supposons :
    
    - Taux marginal aujourd’hui : 40 %  
  - Taux marginal à la retraite : 30 %  
  - Cotisation : 1 000 \$  
    
    **À la cotisation :**  
    - Économie d’impôt immédiate : 400 \$  
    - Coût net : 600 \$  
    
    **À la retraite :**  
    - Retrait de 1 000 \$  
    - Impôt payé : 300 \$  
    - Montant net : 700 \$  
    
    **Lecture du mécanisme :**  
    - On investit effectivement 600 \$  
    - On récupère 700 \$  
    - Le gain provient uniquement de la différence de taux (40 % → 30 %)  
  :::
    
    Si les taux sont identiques, le REER devient essentiellement neutre (hors rendement). Si le taux à la retraite est plus élevé, le mécanisme devient défavorable. Il est important de noter que les revenus de placement à l’intérieur d’un REER ne sont pas imposés au fur et à mesure qu’ils sont générés. Cela permet une capitalisation à l’abri de l’impôt (intérêt sur intérêt). Toutefois, cet avantage n’est pas spécifique au REER : il est compensé par l’imposition complète des sommes au moment du retrait. Le véritable levier du REER réside donc dans l’arbitrage entre les taux d’imposition dans le temps, et non dans la seule capitalisation.
  
  
  #### **CELI : absence d’imposition, mais sans déduction** 
  
  Le CELI inverse la logique du REER : aucune déduction à l’entrée, mais aucune imposition à la sortie. Contrairement au REER, il n’y a donc pas d’arbitrage entre deux taux d’imposition dans le temps. L’avantage central du CELI provient du fait que les revenus de placement (intérêts, dividendes, gains en capital) ne sont jamais imposés. Cela permet une capitalisation complète des rendements, sans érosion fiscale, ce qui devient particulièrement significatif à long terme.
  
  ::: {#exm-6 .custom}
    Supposons :
      
      - Taux marginal : 40 %  
    - Montant disponible : 1 000 \$  
      
      **Avant investissement :**  
      - Impôt payé : 400 \$  
      - Montant investi : 600 \$  
      
      **À la sortie :**  
      - Aucun impôt  
    - Montant net : 600 \$ + rendement  
    :::
      
      Contrairement au REER, cet avantage ne dépend pas du taux d’imposition futur. Le CELI offre donc une structure plus stable : une fois l’impôt payé à l’entrée, l’évolution du contexte fiscal n’affecte plus la valeur nette accumulée. Cette caractéristique le rend particulièrement robuste en présence d’incertitude sur les taux d’imposition futurs.
    